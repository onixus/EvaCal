/**
 * Русскоязычные лексиконы для валидаторов требований.
 *
 * Границы слов (`\b`) в JS работают только по ASCII, поэтому для кириллицы
 * используются явные разделители через `BOUND` вместо `\b`.
 */

/** Начало слова: начало строки или не-буквенный символ. */
const BOUND = '(?:^|[^0-9a-zа-яё])';

function wordish(...alternatives: string[]): RegExp {
  return new RegExp(`${BOUND}(?:${alternatives.join('|')})`, 'iu');
}

/** Обязывающая формулировка: без неё текст — не требование, а описание. */
export const MODAL_PATTERN = wordish(
  'должн[а-яё]*',
  'обязан[а-яё]*',
  'подлежит',
  'подлежат',
  'следует',
  'необходимо',
  'требуется'
);

/** Все вхождения обязывающих формулировок — для проверки единичности. */
export const MODAL_PATTERN_GLOBAL = new RegExp(MODAL_PATTERN.source, 'giu');

/** Отрицание перед обязывающей формулировкой. */
export const NEGATION_PATTERN = new RegExp(`${BOUND}не\\s+(?:должн|обязан|допускается|разрешается)`, 'iu');

