/** Верхняя граница показателя: «не более 2 с», «≤ 15 мин». */
export const UPPER_BOUND_PATTERN =
  /(?:не\s+(?:более|выше|превыша[а-яё]+|позднее)|≤|<=|<)\s*([\d]+(?:[.,]\d+)?)\s*([a-zа-яё%]+)?/iu;

/** Нижняя граница показателя: «не менее 99,9 %». */
export const LOWER_BOUND_PATTERN =
  /(?:не\s+(?:менее|ниже|хуже)|≥|>=|>)\s*([\d]+(?:[.,]\d+)?)\s*([a-zа-яё%]+)?/iu;

export function hasMeasurableValue(text: string): boolean {
  return MEASURE_PATTERNS.some((pattern) => pattern.test(text));
}

export function findVagueTerms(text: string): string[] {
  return VAGUE_TERMS.filter((term) => term.pattern.test(text)).map((term) => term.label);
}

export function parseNumber(raw: string): number {
  return Number(raw.replace(',', '.'));
}
