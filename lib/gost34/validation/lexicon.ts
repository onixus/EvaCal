/** Числовое значение с единицей измерения или явной границей. */
export const MEASURE_PATTERNS: RegExp[] = [
  /\d[\d\s.,]*\s*(?:%|проц)/iu,
  /\d[\d\s.,]*\s*(?:мс|сек|секунд[а-яё]*|мин|минут[а-яё]*|час[а-яё]*|ч\.|сут[а-яё]*|дн[а-яё]*|недел[а-яё]*|месяц[а-яё]*|год[а-яё]*|лет)/iu,
  /\d[\d\s.,]*\s*(?:кб|мб|гб|тб|кбайт|мбайт|гбайт|тбайт|кбит|мбит|гбит)/iu,
  /\d[\d\s.,]*\s*(?:пользовател[а-яё]*|запрос[а-яё]*|транзакц[а-яё]*|операц[а-яё]*|сеанс[а-яё]*|документ[а-яё]*|шт)/iu,
  /(?:^|[^0-9a-zа-яё])(?:не\s+(?:более|менее|ниже|выше|хуже|превыша[а-яё]+)|≤|≥|<=|>=)\s*[\d«"]/iu,
  /(?:^|[^0-9a-zа-яё])(?:rto|rpo|sla|tps|rps)\b/iu,
];

